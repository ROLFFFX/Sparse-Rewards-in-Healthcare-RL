"""
Tabular MDPs for the theory experiments: the LifeGate gridworld, the random DAG MDPs of the original paper and
the empirical MIMIC-III sepsis MDP.

LifeGate and the DAG MDPs are built by the generators in LifeGate-Gridworld/ and DAG-Based-MDP-MRP/; only
their transition structure is used, and rewards are re-derived from the terminal sets (see `tabular`).
"""
import os
import sys
import types
import warnings

import numpy as np
import pandas as pd

from tabular import DEATH, SURVIVAL, TRANSIENT, TabularMDP

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
MIMIC_DATA = os.path.join(REPO, 'mimic-sepsis', 'data')


# --- LifeGate (LifeGate-Gridworld/gridworld.py) -------------------------------
LG_N = 10
LG_INVALIDS = [(0, 0), (0, 1), (0, 2), (0, 3), (0, 4), (5, 1), (5, 2), (5, 3), (5, 4)]
LG_SURVIVALS = [(0, 5), (0, 6), (0, 7)]
LG_MORTALITIES = [(0, 8), (0, 9), (1, 9), (2, 9), (3, 9), (4, 9), (5, 9), (6, 9), (7, 9), (8, 9), (9, 9)]


def lifegate(slip_prob=0.2):
    """
    The 10 x 10 LifeGate gridworld exactly as built by LifeGate-Gridworld/gridworld.py:get_gridworld
    (state x * 10 + y, 4 actions). d0 is uniform over the non-terminal, non-wall cells.
    """
    sys.path.insert(0, os.path.join(REPO, 'LifeGate-Gridworld'))
    from gridworld import get_gridworld
    source = get_gridworld(mode='mixed', slip_prob=slip_prob)
    S, A = LG_N * LG_N, 4
    P = np.zeros((S, A, S))
    mask = np.zeros((S, A), dtype=bool)
    kind = np.full(S, TRANSIENT)
    for (x, y) in LG_SURVIVALS:
        kind[x * LG_N + y] = SURVIVAL
    for (x, y) in LG_MORTALITIES:
        kind[x * LG_N + y] = DEATH
    walls = np.zeros(S, dtype=bool)
    for (x, y) in LG_INVALIDS:
        walls[x * LG_N + y] = True
    for s in range(S):
        if kind[s] != TRANSIENT or walls[s]:
            continue
        for a, outcomes in source[s].items():
            mask[s, a] = True
            for p, s_next, _ in outcomes:
                P[s, a, s_next] += p
    report = (kind == TRANSIENT) & ~walls
    return TabularMDP.from_numpy(P, mask, kind, d0=report.astype(float), report=report,
                                 name=f'LifeGate (slip {slip_prob})', meta={'grid': LG_N, 'walls': walls})


# --- random DAG MDPs of the original paper (DAG-Based-MDP-MRP/mdp/lifegate_mdp.py) ----
def dag(max_num_states=200, p_terminal=0.3, max_actions=2, seed=28, trap=False, flip=False):
    """
    The DAG MDPs of the original paper, generated by DAG-Based-MDP-MRP/mdp/lifegate_mdp.py with its seeds
    (toy: 5 states, large: 200 states; p_terminal = 0.3, 2 actions, seed 28). trap=True applies the
    modification of break_absorption.py (a non-terminal absorbing state s3 reachable from s1 and s2);
    flip=True swaps recovery and death as in invert_classes.py. d0 is the root s0.
    """
    if 'graphviz' not in sys.modules:                  # only used for drawing in the original module
        stub = types.ModuleType('graphviz')
        stub.Digraph = object
        sys.modules['graphviz'] = stub
    sys.path.insert(0, os.path.join(REPO, 'DAG-Based-MDP-MRP', 'mdp'))
    with warnings.catch_warnings():
        warnings.simplefilter('ignore')
        from lifegate_mdp import LifeGate_MDP
    source = LifeGate_MDP(max_num_states=max_num_states, p_terminal=p_terminal, max_actions=max_actions,
                          seed=seed, mode='+-')
    # transitions[state][action][next_state] = (probability, reward)
    transitions = {s: {a: dict(nxt) for a, nxt in acts.items()} for s, acts in source.transitions.items()}
    states = list(source.states)
    if trap:                                           # exactly as in break_absorption.py
        states.append('s3')
        transitions['s3'] = {'0': {'s3': (1.0, 0.0)}, '1': {'s3': (1.0, 0.0)}}
        transitions['s1']['1']['s3'] = (0.48, 0.0)
        transitions['s1']['1']['recovery'] = (0.52, 1.0)
        del transitions['s1']['1']['death']
        transitions['s2']['1']['recovery'] = (0.5, 1.0)
        transitions['s2']['1']['s3'] = (0.5, 0.0)
    idx = {s: i for i, s in enumerate(states)}
    S, A = len(states), len(source.actions)
    P = np.zeros((S, A, S))
    mask = np.zeros((S, A), dtype=bool)
    kind = np.full(S, TRANSIENT)
    kind[idx['recovery']], kind[idx['death']] = (DEATH, SURVIVAL) if flip else (SURVIVAL, DEATH)
    for s, acts in transitions.items():
        if kind[idx[s]] != TRANSIENT:
            continue
        for ai, a in enumerate(source.actions):
            if a in acts:
                mask[idx[s], ai] = True
                for nxt, (p, _) in acts[a].items():
                    P[idx[s], ai, idx[nxt]] += p
    assert np.allclose(P[mask].sum(-1), 1.0), 'rows of the original DAG must be normalized'
    d0 = np.zeros(S)
    d0[idx['s0']] = 1.0
    name = (f"DAG MDP ({max_num_states} states, p_terminal {p_terminal}, seed {seed}"
            f"{', trap state' if trap else ''}{', flipped' if flip else ''})")
    return TabularMDP.from_numpy(P, mask, kind, d0=d0, name=name, meta={'states': states})


# --- MIMIC-III sepsis (mimic-sepsis/pipeline/1-env_model_variants.ipynb) ------
MIMIC_NS, MIMIC_NA = 750, 25
S_SURVIVAL, S_DEATH = 750, 751


def mimic(data_dir=MIMIC_DATA, split='train'):
    """
    Empirical transition model from traj_shifted_<split>.csv, built as in
    mimic-sepsis/pipeline/1-env_model_variants.ipynb and restricted to the clinician-supported actions of
    behavior_policy/SA_mask_shifted.pkl. States 0..749 are clusters, 750 survival, 751 death; d0 is the
    empirical distribution of first states. meta['pi_b'] (S, A) is the empirical clinician policy on the
    admissible actions.
    """
    df = pd.read_csv(os.path.join(data_dir, f'traj_shifted_{split}.csv'),
                     dtype={'a:action': 'Int64', 'a:next_action': 'Int64'})
    S = MIMIC_NS + 2
    counts = np.zeros((S, MIMIC_NA, S))
    sas = df.groupby(['s:state', 'a:action', 's:next_state']).size()
    for (s, a, s_next), c in sas.items():
        counts[int(s), int(a), int(s_next)] = c
    n_sa = counts.sum(-1, keepdims=True)
    P = np.divide(counts, n_sa, out=np.zeros_like(counts), where=n_sa > 0)
    observed = n_sa[..., 0] > 0

    SA_mask = pd.read_pickle(os.path.join(data_dir, 'behavior_policy', 'SA_mask_shifted.pkl'))
    SA_mask = np.asarray(SA_mask.values if isinstance(SA_mask, pd.DataFrame) else SA_mask, dtype=bool)
    mask = np.zeros((S, MIMIC_NA), dtype=bool)
    mask[:MIMIC_NS] = SA_mask[:MIMIC_NS] & observed[:MIMIC_NS]
    kind = np.full(S, TRANSIENT)
    kind[S_SURVIVAL], kind[S_DEATH] = SURVIVAL, DEATH

    first = df.sort_values(['traj', 'step']).groupby('traj')['s:state'].first().astype(int)
    d0 = np.bincount(first, minlength=S).astype(float)

    admissible_counts = counts.sum(-1) * mask
    n_s = admissible_counts.sum(-1, keepdims=True)
    pi_b = np.divide(admissible_counts, n_s, out=np.zeros_like(admissible_counts), where=n_s > 0)
    report = mask.any(1)
    meta = {'pi_b': pi_b, 'n_traj': df['traj'].nunique(), 'n_transitions': len(df),
            'no_action_states': int((~mask[:MIMIC_NS].any(1)).sum())}
    return TabularMDP.from_numpy(P, mask, kind, d0=d0, report=report, name='MIMIC-III sepsis', meta=meta)
